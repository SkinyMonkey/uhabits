import SwiftUI
import UIKit
import class UhabitsCore.IosSettings
import class UhabitsCore.Preferences
import class UhabitsCore.UserDefaultsStorage

/// Settings screen, the counterpart of Android's preferences.xml. Bound to the shared Kotlin Preferences.
struct SettingsView: View {
    @EnvironmentObject var store: HabitStore
    @State private var shareURL: URL?
    @State private var importing = false
    @State private var message: String?
    @State private var refresh = 0 // bumped on every write so the Kotlin-backed bindings re-read

    private var prefs: Preferences { store.graph.preferences }
    private let ios = IosSettings(storage: UserDefaultsStorage(defaults: .standard))

    private func binding<T>(_ get: @escaping () -> T, _ set: @escaping (T) -> Void) -> Binding<T> {
        Binding(get: { _ = refresh; return get() }, set: { set($0); refresh += 1 })
    }

    var body: some View {
        Form {
            Section("Interface") {
                Toggle("Toggle with short press", isOn: binding({ prefs.isShortToggleEnabled }, { prefs.isShortToggleEnabled = $0 }))
                Toggle(isOn: binding({ prefs.isMidnightDelayEnabled }, { prefs.isMidnightDelayEnabled = $0; store.reload() })) {
                    Text("Extend day a few hours past midnight")
                    Text("Wait until 3:00 AM to show a new day.")
                }
                Toggle(isOn: binding({ prefs.isSkipEnabled }, { prefs.isSkipEnabled = $0 })) {
                    Text("Enable skip days")
                    Text("Toggle twice to add a skip instead of a checkmark.")
                }
                Toggle(isOn: binding({ prefs.areQuestionMarksEnabled }, { prefs.areQuestionMarksEnabled = $0 })) {
                    Text("Show question marks for missing data")
                    Text("Differentiate days without data from actual lapses.")
                }
                Toggle(isOn: binding({ prefs.isCheckmarkSequenceReversed }, { prefs.isCheckmarkSequenceReversed = $0 })) {
                    Text("Reverse order of days")
                    Text("Show days in reverse order on the main screen.")
                }
                Toggle("Disable animations", isOn: binding({ prefs.isConfettiAnimationDisabled }, { prefs.isConfettiAnimationDisabled = $0 }))
                Picker("Theme", selection: binding({ Int(prefs.theme) }, { prefs.theme = Int32($0) })) {
                    Text("System").tag(0)
                    Text("Light").tag(2)
                    Text("Dark").tag(1)
                }
                Picker("First day of the week", selection: binding({ Int(ios.firstWeekday) }, { ios.firstWeekday = Int32($0); store.reload() })) {
                    Text("System default").tag(-1)
                    ForEach(1...7, id: \.self) { d in Text(Calendar.current.weekdaySymbols[d - 1]).tag(d) }
                }
            }

            Section("Reminders") {
                Picker("Snooze interval", selection: binding({ Int(ios.snoozeMinutes) }, { ios.snoozeMinutes = Int32($0) })) {
                    ForEach([15, 30, 60, 120, 240, 480], id: \.self) { m in
                        Text(m < 60 ? "\(m) minutes" : "\(m / 60) hour\(m == 60 ? "" : "s")").tag(m)
                    }
                }
                Button("Notification settings") {
                    if let url = URL(string: UIApplication.openNotificationSettingsURLString) { UIApplication.shared.open(url) }
                }
            }

            Section("Database") {
                Button { export { try store.importExport.exportDB(outputDir: $0) } } label: {
                    Text("Export full backup")
                    Text("Generates a file that contains all your data. This file can be imported back.").font(.caption).foregroundStyle(.secondary)
                }
                Button { export { try store.importExport.exportCSV(outputDir: $0) } } label: {
                    Text("Export as CSV")
                    Text("Generates files that can be opened by spreadsheet software.").font(.caption).foregroundStyle(.secondary)
                }
                Button { importing = true } label: {
                    Text("Import data")
                    Text("Supports full backups exported by this app, as well as files generated by Tickmate, HabitBull or Rewire.").font(.caption).foregroundStyle(.secondary)
                }
            }

            Section("About") {
                LabeledContent("Version", value: Self.version)
                Link("View source code at GitHub", destination: URL(string: "https://github.com/iSoron/uhabits")!)
                Link("Help & FAQ", destination: URL(string: "http://loophabits.org/faq.html")!)
            }
        }
        .navigationTitle("Settings")
        .fileImporter(isPresented: $importing, allowedContentTypes: [.item]) { result in
            if case .success(let url) = result { importFile(url) }
        }
        .sheet(item: $shareURL) { ShareSheet(url: $0) }
        .alert(message ?? "", isPresented: Binding(get: { message != nil }, set: { if !$0 { message = nil } })) {}
    }

    static var version: String {
        let info = Bundle.main.infoDictionary ?? [:]
        return "\(info["CFBundleShortVersionString"] as? String ?? "?") (\(info["CFBundleVersion"] as? String ?? "?"))"
    }

    /// Writes into a fresh temp folder and opens the share sheet on the result.
    private func export(_ write: (String) throws -> String) {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("export-\(UUID().uuidString)")
        do {
            shareURL = URL(fileURLWithPath: try write(dir.path))
        } catch {
            message = "Export failed: \(error.localizedDescription)"
        }
    }

    private func importFile(_ url: URL) {
        let scoped = url.startAccessingSecurityScopedResource()
        defer { if scoped { url.stopAccessingSecurityScopedResource() } }
        // Import from a copy: Loop backups are migrated in place
        let copy = FileManager.default.temporaryDirectory.appendingPathComponent("import-\(UUID().uuidString)-\(url.lastPathComponent)")
        do {
            try FileManager.default.copyItem(at: url, to: copy)
            defer { try? FileManager.default.removeItem(at: copy) }
            try store.importExport.importFile(path: copy.path)
            message = "Habits imported successfully."
        } catch {
            message = "Import failed: \(error.localizedDescription)"
        }
    }
}

extension URL: @retroactive Identifiable {
    public var id: String { absoluteString }
}

private struct ShareSheet: UIViewControllerRepresentable {
    let url: URL
    func makeUIViewController(context: Context) -> UIActivityViewController {
        UIActivityViewController(activityItems: [url], applicationActivities: nil)
    }
    func updateUIViewController(_ controller: UIActivityViewController, context: Context) {}
}
